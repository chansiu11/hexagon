'use strict';
// Extract existing normal-stage formations; stage seven mixes these motifs.
const fs=require('node:fs');
const {Game}=require('./engine');
const bank=[];
for(let level=0;level<6;level++){
 const source=require('./assets/timelines/waves-stage-'+level+'.json'),g=new Game(level,source);
 const events=g.timeline.waves.map(w=>({id:w.id,time:w.start+(w.r-78)/w.speed}))
  .filter(w=>w.time>2&&w.time<58&&source.shapeSchedule.every(([at])=>Math.abs(w.time-at)>.8))
  .sort((a,b)=>a.time-b.time);
 const groups=[];
 for(const event of events){const last=groups.at(-1);if(last&&event.time-last.time<.14)last.ids.push(event.id);else groups.push({time:event.time,ids:[event.id]})}
 const gates=[];
 for(const group of groups){
  g.time=group.time;g.sampleWalls();
  const members=g.walls.filter(w=>group.ids.includes(w.waveId));
  const sectors=[...new Set(members.map(w=>w.toSector??Math.floor((w.sector+.5)*g.sides/w.sides)))].sort((a,b)=>a-b);
  if(sectors.length<Math.max(1,g.sides-3)||sectors.length>=g.sides)continue;
  const thickness=members.reduce((s,w)=>s+w.thickness,0)/members.length;
  gates.push({sides:g.sides,sectors,thickness:+thickness.toFixed(2),time:+group.time.toFixed(3),sourceIds:group.ids});
 }
 for(let i=0;i+3<gates.length;i+=3){
  bank.push({id:level+':'+i,level,gates:gates.slice(i,i+4).map((w,k)=>({...w,gap:k?+(w.time-gates[i+k-1].time).toFixed(3):.5}))});
 }
 console.log('stage',level+1,gates.length,'formations');
}
if(new Set(bank.map(p=>p.level)).size!==6)throw Error('All six normal stages must supply patterns');
const output='/* Generated by build_pattern_bank.cjs from the unchanged normal wall timelines. */\n(function(root){const bank='+JSON.stringify(bank)+';if(typeof module!=="undefined"&&module.exports)module.exports=bank;else root.HexPatternBank=bank;})(typeof window!=="undefined"?window:globalThis);\n';
fs.writeFileSync('pattern-bank.js',output);console.log(bank.length,'four-gate source motifs');
